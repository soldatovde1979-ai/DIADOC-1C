import difflib, os, sys, json, re
from collections import defaultdict, Counter
ROOT=sys.argv[1]; OUT=sys.argv[2]
sys.path.insert(0, os.path.dirname(__file__))
src=open(os.path.join(os.path.dirname(__file__),'inventory.py'),encoding='utf-8').read()
FILES=eval(re.search(r'FILES=(\[.*?\n\])',src,re.S).group(1))
ns={}; exec(re.search(r'(def pos\(.*?\n)(?=FUNC=)',src,re.S).group(1),{'re':re},ns); pos=ns['pos']
E=os.path.join(ROOT,'SRC/ERPDiadok'); T=os.path.join(ROOT,'SRC/TypeDiadok')
FUNC=re.compile(r'^\s*(?:Асинх\s+)?(Функция|Процедура)\s+([\wА-Яа-яЁё]+)\s*\(', re.I)
SURN=['Кошелев','Красавин','Калашников','Персианов','Гирфанов','Никоноров']
DATE=re.compile(r'(\d{4}[-.]\d{2}[-.]\d{2}|\d{2}[-.]\d{2}[-.]\d{4})')
TASK=re.compile(r'00-000\d{5}')
rows=[]
for rel,short in FILES:
    a=open(os.path.join(T,rel),encoding='utf-8-sig').read().splitlines()
    b=open(os.path.join(E,rel),encoding='utf-8-sig').read().splitlines()
    owner=[]; cur=None
    for l in b:
        m=FUNC.match(l)
        if m: cur=m.group(2)
        owner.append(cur)
    for tag,i1,i2,j1,j2 in difflib.SequenceMatcher(None,a,b,autojunk=False).get_opcodes():
        if tag=='equal': continue
        add=b[j1:j2]; rem=a[i1:i2]; txt='\n'.join(add+rem)
        if not txt.strip(): continue  # пустые строки
        func=owner[min(j1,len(b)-1)]
        hdr=[FUNC.match(l).group(2) for l in add if FUNC.match(l)]
        if hdr and (func is None or j1<len(b) and FUNC.match(b[j1])): func=hdr[0]
        authors=[s for s in SURN if s in txt]; dates=DATE.findall(txt); tasks=sorted(set(TASK.findall(txt)))
        marked=bool(re.search('шх',txt,re.I)) or 'т1к' in txt
        rows.append(dict(file=short,line=j1+1,func=func or '(уровень модуля)',add=len(add),rem=len(rem),pos=pos(short,func,txt),
            authors=', '.join(authors),date=(dates[0] if dates else ''),tasks=', '.join(tasks),marked=marked,sig=bool(hdr) and bool(rem) and any(FUNC.match(l) for l in rem)))
NAMES={2:'Доп. ПФ «Сверка (ШХ)» / ПФ строкой',4:'Экспорт Ядро',5:'Ошибки ИнтеграцияУТ11',6:'т1кПараметры в СтандартУФ',7:'НаимЕдИзм (ГенерацияXML)',8:'Договор1С в Ядре',9:'Отправитель/получатель в событие ПМ',10:'Настройки контракта ядра',11:'КС расширения',12:'ПФ и пакеты, УПД970',13:'Договор1С в ХранениеДанных',14:'Хранение в прикреплённых файлах',15:'РежимПользователя в списке пакетов',16:'Команда формирования документов',17:'ФормаУправляемая',18:'ФормаЭлементаСправочника',19:'НастройкаПечатныхФорм',20:'НастройкиУправляемая',21:'ФормаПакета',24:'НОВАЯ: автоматизация создания документов (ИнтеграцияУТ11 УФ)',25:'НОВАЯ: единица измерения (ИнтеграцияУниверсальный)',26:'НОВАЯ: массовое подписание документов'}
by=defaultdict(list)
for r in rows: by[r['pos']].append(r)
L=[]
w=L.append
w('# R1. Опись нашей дельты в коде вендора (4.61.1)\n')
w('> Версия: 1.0 · 07.10.2026 · Сделано автоматически: построчное сравнение `SRC/TypeDiadok` (дистрибутив) и `SRC/ERPDiadok` (наш прод) по всем изменённым `.bsl`.')
w('> Скрипт-генератор — `tools/research/inventory.py` (запуск: `python3 tools/research/inventory.py <корень репо>`). Пустые строки не считаются.\n')
w('## Главное\n')
tot_add=sum(r['add'] for r in rows); tot_rem=sum(r['rem'] for r in rows)
w(f'- Изменено **14** файлов вендора (а не 12, как было записано раньше) + наш новый `ДД_подключаемыйМодуль`.')
w(f'- Мест правок: **{len(rows)}**, строк добавлено **{tot_add}**, удалено **{tot_rem}**.')
w(f'- Мест **без маркера** `ШХ`/`шх`/`т1к`: **{sum(1 for r in rows if not r["marked"])}** — в основном изменённые сигнатуры и вызовы (добавлен параметр), см. колонку «Маркер».')
w('- Маркер встречается в обоих регистрах: `ШХ` и `шх`. Строк с маркером без учёта регистра — 332 в 15 файлах (раньше считалось 222 — поиск был чувствителен к регистру).')
w('- **В реестре не было трёх доработок** — добавлены как позиции 24, 25, 26 (подробно ниже).')
w('- **Доработка позиции 26 меняет метаданные основной конфигурации**: в справочник вендорского хранилища `Диадок_Документы` добавлены реквизиты `ЭтапПодписания`, `Подписывает`, `Процесс`, `Этап`. Этот справочник вендор ставит в основную конфигурацию своим `.cf` (макет `ОбновлениеДляХраненияДанных_cf`). В репозитории основной конфигурации нет — нужно проверить руками (см. ТЗ-0, С12).\n')
w('## Сводка по позициям реестра\n')
w('| Поз. | Что | Мест | +строк | −строк | Без маркера | Авторы | Задачи |')
w('|---|---|---|---|---|---|---|---|')
for p in sorted(by):
    rs=by[p]
    au=', '.join(sorted({a for r in rs for a in r['authors'].split(', ') if a}))
    tk=', '.join(sorted({t for r in rs for t in r['tasks'].split(', ') if t}))
    w(f"| {p} | {NAMES.get(p,'?')} | {len(rs)} | {sum(r['add'] for r in rs)} | {sum(r['rem'] for r in rs)} | {sum(1 for r in rs if not r['marked'])} | {au} | {tk} |")
w(f"| **Итого** | | **{len(rows)}** | **{tot_add}** | **{tot_rem}** | **{sum(1 for r in rows if not r['marked'])}** | | |\n")
w('## Новые позиции (в реестре их не было)\n')
w('| Поз. | Файл | Что делает | Действие v3 |')
w('|---|---|---|---|')
w('| 24 | `КонтурДиадокСтандартУФ_Модуль_ИнтеграцияУТ11` (+1 место в `Ядро.ТиповойМодуль_СоздатьДокумент`) | Автоматизация ЭДО при создании документов поступления: договор/склад/подразделение из `т1кПараметры`, статья и аналитика расходов, «не списывать на расходы», авто-создание номенклатуры при регламентном создании, номер/дата исправления СФ, постобработка `т1кДиадокСервер.ПостобработкаЗаполненияПриобретенияТоваровУслуг` | Вынос тел в `т1кДиадокМодули` + точки вызова (ТЗ-3, этап 2); остаток — встроенная дельта |')
w('| 25 | `КонтурДиадокСтандартУФ_Модуль_ИнтеграцияУниверсальный` | Единица измерения в данных и представлении номенклатуры (пара к позиции 7, исходящая сторона) | Встроенная дельта, 3 строки (ТЗ-4) |')
w('| 26 | `Ядро` (`Документы_ПослеОтправкиMessagePatchToPost`, `Контракт_Документ`), `ХранениеДанных` (`Документы_ТекстЗапросаЗаполненияКонтракта`, `Документы_КонтрактДокументаПоВыборке_Диадок`, `Документы_ОбновлениеРеквизитов_Диадок`) + реквизиты справочника `Диадок_Документы` в основной конфигурации | Массовое подписание документов (Калашников, 00-00020261): этап подписания, автосогласование после отправки. Формы — в поз. 17, отбор — в поз. 10, 15 | Встроенная дельта (ТЗ-4) + **проверить метаданные основной конфигурации** (ТЗ-0, С12) |\n')
w('## Полный список мест\n')
w('Сигнатура = в этом месте изменён заголовок функции (добавлен параметр) — такие места контролирует сигнатурный контроль ТЗ-5 (Б3).\n')
w('| № | Файл | Строка (прод) | Функция | +/− | Поз. | Маркер | Сигнатура | Автор | Дата | Задача |')
w('|---|---|---|---|---|---|---|---|---|---|---|')
for i,r in enumerate(sorted(rows,key=lambda r:(r['pos'],r['file'],r['line'])),1):
    w(f"| {i} | {r['file']} | {r['line']} | `{r['func']}` | +{r['add']}/−{r['rem']} | {r['pos']} | {'да' if r['marked'] else '**нет**'} | {'да' if r['sig'] else ''} | {r['authors']} | {r['date']} | {r['tasks']} |")
open(OUT,'w',encoding='utf-8').write('\n'.join(L)+'\n')
